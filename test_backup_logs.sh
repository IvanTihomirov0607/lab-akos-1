#!/bin/bash
GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m'

PASS=0
FAIL=0

check() {
    if [ "$1" -eq 0 ]; then
        echo -e "${GREEN}[OK]${NC} $2"
        PASS=$((PASS + 1))
    else
        echo -e "${RED}[FAIL]${NC} $2"
        FAIL=$((FAIL + 1))
    fi
}

echo "-=-=-=-ЗАПУСК ТЕСТОВ ДЛЯ backup_logs.sh-=-=-=-"

##############################################################
echo -e "\nТест 1 - запуск без аргументов (ожидается ошибка)"
./backup_logs.sh >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при отсутствии аргументов"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

################################################################
echo -e "\nТест 2 - запуск с несуществующей папкой (ожидается ошибка)"
./backup_logs.sh /no_such_folder 50 2 >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при вводе несуществующей папки"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

################################################################
echo -e "\nТест 3 - Ввод букв вместо порога (ожидается ошибка)"
./backup_logs.sh /log abc 3 >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при вводе букв"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

#################################################################
echo -e "\nТест 4 - Ввод букв вместо кол-ва файлов (ожидается ошибка)"
./backup_logs.sh /log 50 abc >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при вводе букв"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

##################################################################
echo -e "\nТест 5 - Ввод отрицательного порога (ожидается ошибка)"
./backup_logs.sh /log -3 3 >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при вводе отрицательного порога"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

###################################################################
echo -e "\nТест 6 - Ввод отрицательного кол-ва файлов (ожидается ошибка)"
./backup_logs.sh /log 50 -3 >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при вводе отрицательного кол-ва файлов"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

###################################################################
echo -e "\nТест 7 - Ввод дробного числа для кол-ва файлов (ожидается ошибка)"
./backup_logs.sh /log 50 3.5 >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -ne 0 ]; then
    check 0 "Скрипт вернул ошибку при вводе дробного кол-ва файлов"
else
    check 1 "Скрипт не вернул ошибку, хотя должен был"
fi

####################################################################
echo -e "\nТест 8 - Ввод дробного числа для порога (ожидается успех)"
./backup_logs.sh /log 50.5 3 >/dev/null 2>&1

RESULT=$?
if [ "$RESULT" -eq 0 ]; then
    check 0 "Скрипт корректно принял дробный порог"
else
    check 1 "Скрипт ошибочно отклонил дробный порог"
fi

#####################################################################
echo -e "\n-=-=- Подготовка тестовой среды -=-=-"
rm -f /log/* /backup/* 2>/dev/null

for i in {1..10}; do
    echo "Данные файла $i" > /log/test_file_$i.txt
done

#################################################################
echo -e "\nТест 9 - порог не превышен (порог 99%)"
./backup_logs.sh /log 99 3 >/dev/null 2>&1

[ -z "$(ls -A /backup)" ]
RESULT=$?

if [ "$RESULT" -eq 0 ]; then
    check 0 "Архив не создан, файлы в /log не тронуты"
else
    check 1 "Ошибка - архив создался, хотя порог не превышен"
fi

####################################################################
echo -e "\nТест 10 - порог превышен (порог 0%)"
./backup_logs.sh /log 0 3 >/dev/null 2>&1
ARCHIVE=$(ls /backup/*.tar.gz 2>/dev/null)
[ -n "$ARCHIVE" ]
RESULT=$?

if [ "$RESULT" -eq 0 ]; then
    check 0 "Архив успешно создан в /backup"
else
    check 1 "Ошибка - архив не был создан"
fi

#####################################################################
echo -e "\nТест 11 - проверка удаления оригиналов"
COUNT=$(ls /log | wc -l)
[ "$COUNT" -eq 7 ]
RESULT=$?

if [ "$RESULT" -eq 0 ]; then
    check 0 "Из /log удалено ровно 3 файла (осталось 7)"
else
    check 1 "Ошибка - удалено неверное количество файлов (осталось $COUNT)"
fi

######################################################################
echo -e "\nТест 12 - проверка содержимого архива"
ARCHIVE_COUNT=$(tar -tzf "$ARCHIVE" | wc -l)
[ "$ARCHIVE_COUNT" -eq 3 ]
RESULT=$?

if [ "$RESULT" -eq 0 ]; then
    check 0 "В архиве лежит ровно 3 файла"
else
    check 1 "Ошибка - в архиве лежит $ARCHIVE_COUNT файлов (ожидалось 3)"
fi

####################################################################
echo -e "\nТест 13 - пустая папка (ожидается успех, архива нет)"
rm -f /log/* /backup/* 2>/dev/null

./backup_logs.sh /log 0 3 >/dev/null 2>&1
RESULT=$? 
ARCHIVE=$(ls /backup/*.tar.gz 2>/dev/null)
[ "$RESULT" -eq 0 ] && [ -z "$ARCHIVE" ]
RESULT=$?

if [ "$RESULT" -eq 0 ]; then
    check 0 "Скрипт корректно завершился с кодом 0 и не создал пустой архив"
else
    check 1 "Ошибка - скрипт упал или создал архив из пустой папки"
fi

####################################################################
echo -e "\nТест 14 - файлов меньше, чем запрошено (ожидается успех)"
rm -f /log/* /backup/* 2>/dev/null
for i in {1..2}; do
    echo "Данные $i" > /log/file_$i.txt
done

./backup_logs.sh /log 0 5 >/dev/null 2>&1
RESULT=$?
ARCHIVE=$(ls /backup/*.tar.gz 2>/dev/null)

if [ "$RESULT" -eq 0 ] && [ -n "$ARCHIVE" ]; then
    ARCHIVE_COUNT=$(tar -tzf "$ARCHIVE" | wc -l)
    [ "$ARCHIVE_COUNT" -eq 2 ]
    RESULT=$?
    if [ "$RESULT" -eq 0 ]; then
        check 0 "Скрипт заархивировал 2 файла, хотя просили 5"
    else
        check 1 "Ошибка - в архиве не 2 файла"
    fi
else
    check 1 "Ошибка - архив не создан"
fi

####################################################################
echo -e "\nТест 15 - файл с пробелом в имени (ожидается успех)"
rm -f /log/* /backup/* 2>/dev/null
echo "тест" > "/log/файл с пробелом.txt"

./backup_logs.sh /log 0 1 >/dev/null 2>&1
RESULT=$?
ARCHIVE=$(ls /backup/*.tar.gz 2>/dev/null)

if [ "$RESULT" -eq 0 ] && [ -n "$ARCHIVE" ]; then
    ARCHIVE_COUNT=$(tar -tzf "$ARCHIVE" | wc -l)
    [ "$ARCHIVE_COUNT" -eq 1 ]
    RESULT=$?
    if [ "$RESULT" -eq 0 ]; then
        check 0 "Скрипт корректно обработал файл с пробелом"
    else
        check 1 "Ошибка - файл с пробелом потерялся"
    fi
else
    check 1 "Ошибка - архив не создан"
fi

echo -e "\n-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=--=-="
echo -e "Пройдено тестов (PASS): ${GREEN}$PASS${NC}"
echo -e "Провалено тестов (FAIL): ${RED}$FAIL${NC}"
echo -e "\n-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=--=-="

if [ "$FAIL" -eq 0 ]; then
    echo -e "${GREEN}ВСЕ ТЕСТЫ ПРОЙДЕНЫ УСПЕШНО!${NC}"
    exit 0
else
    echo -e "${RED}ЕСТЬ ОШИБКИ В РАБОТЕ СКРИПТА${NC}"
    exit 1
fi
